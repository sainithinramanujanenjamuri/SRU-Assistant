"""Data models and exceptions for grounded generation, context construction, and RAG response."""
from __future__ import annotations



from typing import Any


from pydantic import BaseModel, Field

from citations.models import CitationItem, CitationVerificationResult

# ==============================================================================
# Exceptions
# ==============================================================================


class GenerationError(Exception):
    """Base exception for generation failures."""


class LLMProviderUnavailableError(GenerationError):
    """Raised when an explicitly requested LLM provider or service (e.g. Ollama daemon) is unavailable."""


class ContextBudgetExceededError(GenerationError):
    """Raised when context construction exceeds configured limits unrecoverably."""


# ==============================================================================
# Domain Models
# ==============================================================================


class RetrievedEvidence(BaseModel):
    """Structured evidence element passed to the context builder and response attribution."""

    chunk_id: str = Field(..., description="Unique chunk identifier")
    document_id: str = Field(..., description="Canonical SHA-256 document identifier")
    document_name: str = Field(default="Unknown Document", description="Human-readable document filename")
    section_path: str = Field(default="N/A", description="Hierarchical section breadcrumb")
    page_info: str = Field(default="p. 1", description="Formatted page citation string")
    text: str = Field(..., description="Full text content of the evidence chunk")
    score: float = Field(..., ge=0.0, le=1.0, description="Normalized retrieval score in [0.0, 1.0]")
    cosine_similarity: float = Field(default=0.0, description="Raw cosine similarity score in [-1.0, 1.0]")
    dense_score: float | None = Field(default=None, description="Normalized dense retrieval score if present")
    lexical_score: float | None = Field(default=None, description="Normalized lexical retrieval score if present")
    rerank_score: float | None = Field(default=None, description="Normalized score from re-ranking step if performed")
    initial_rank: int | None = Field(default=None, description="Rank prior to re-ranking")
    rerank_rank: int | None = Field(default=None, description="Rank after re-ranking")
    reranker_name: str | None = Field(default=None, description="Identifier of reranker used")
    metadata: dict[str, Any] = Field(default_factory=dict, description="Retained chunk metadata")


class RAGPromptContext(BaseModel):
    """Structured evidence package assembled by the ContextBuilder for answer synthesis."""

    query: str = Field(..., description="User question")
    evidence_items: list[RetrievedEvidence] = Field(
        default_factory=list, description="Ordered list of evidence chunks included in context"
    )
    formatted_context_text: str = Field(
        default="", description="Sanitized and formatted evidence blocks ready for prompt injection"
    )
    total_evidence_tokens: int = Field(
        default=0, ge=0, description="Estimated token count of the included evidence"
    )
    has_sufficient_evidence: bool = Field(
        default=False, description="Flag indicating whether surviving evidence meets relevance thresholds"
    )


class GenerationResponse(BaseModel):
    """Standardized output from a generation backend (deterministic baseline or neural LLM)."""

    text: str = Field(..., description="Generated text answer")
    model_name: str = Field(..., description="Model identifier used for generation")
    provider_name: str = Field(..., description="Generator provider name (e.g. 'deterministic', 'ollama')")
    is_llm: bool = Field(
        ..., description="True if generated by an actual neural LLM, False if produced by rule-based baseline"
    )
    prompt_tokens: int = Field(default=0, ge=0, description="Prompt token count if available")
    completion_tokens: int = Field(default=0, ge=0, description="Completion token count if available")
    latency_ms: float = Field(default=0.0, ge=0.0, description="Measured generator latency in milliseconds")
    thinking: str | None = Field(default=None, description="Optional internal model reasoning trace if present")


class ConflictReport(BaseModel):
    """Structured report of detected factual discrepancies across retrieved institutional evidence."""

    has_conflict: bool = Field(default=False, description="Flag indicating if a discrepancy was detected")
    conflict_type: str | None = Field(
        default=None,
        description="Type of conflict: 'date_discrepancy', 'policy_discrepancy', or 'regulation_discrepancy'",
    )
    conflicting_sources: list[str] = Field(
        default_factory=list, description="List of source filenames or identifiers involved in the discrepancy"
    )
    details: list[str] = Field(
        default_factory=list, description="Human-readable descriptions of the aligned conflicting assertions"
    )


class GroundingValidationResult(BaseModel):
    """Deterministic grounding-support audit of a generated answer against generation evidence.

    IMPORTANT ARCHITECTURAL PRINCIPLE:
    This validation provides a deterministic approximation of grounding support and entity containment,
    NOT a scientifically validated or complete semantic faithfulness metric.
    """

    is_grounded: bool = Field(
        ..., description="True if answer satisfies entity containment and statement support thresholds"
    )
    faithfulness_score: float = Field(
        ...,
        ge=0.0,
        le=1.0,
        description="Deterministic grounding-support approximation in [0.0, 1.0] (heuristic combination)",
    )
    ungrounded_entities: list[str] = Field(
        default_factory=list,
        description="Academic entities mentioned in the answer that do not appear in the evidence",
    )
    supported_statements_count: int = Field(
        default=0, ge=0, description="Count of answer statements aligned with evidence statements"
    )
    unsupported_statements_count: int = Field(
        default=0, ge=0, description="Count of answer statements lacking evidence support"
    )
    entity_coverage: float = Field(
        default=1.0, ge=0.0, le=1.0, description="Ratio of verified answer entities present in evidence"
    )
    token_overlap: float = Field(
        default=1.0, ge=0.0, le=1.0, description="Important token overlap ratio between answer and evidence"
    )
    statement_support: float = Field(
        default=1.0, ge=0.0, le=1.0, description="Proportion of answer statements verified against evidence"
    )
    conflict_report: ConflictReport | None = Field(
        default=None, description="Institutional conflict information associated with the evidence"
    )
    remediation_applied: bool = Field(
        default=False, description="Flag indicating whether strict grounding remediation was executed"
    )


class RAGResponse(BaseModel):
    """End-to-end response produced by the Baseline RAG pipeline with source attribution and observability."""

    query: str = Field(..., description="Original user query")
    answer: str = Field(..., description="Synthesized grounded answer or institutional fallback")
    evidence: list[RetrievedEvidence] = Field(
        default_factory=list, description="Source evidence items used for generation"
    )
    is_grounded: bool = Field(
        ..., description="True if answer is synthesized from retrieved evidence; False if fallback response"
    )
    generator_name: str = Field(..., description="Model/generator identifier")
    provider_name: str = Field(..., description="Generator provider identifier")
    is_llm: bool = Field(..., description="True if produced by neural LLM, False if rule-based baseline")
    retrieval_mode: str = Field(default="dense", description="Retrieval mode used ('dense', 'lexical', 'hybrid')")
    retrieval_latency_ms: float = Field(default=0.0, ge=0.0, description="Search retrieval latency in ms")
    context_latency_ms: float = Field(default=0.0, ge=0.0, description="Context construction latency in ms")
    conflict_latency_ms: float = Field(default=0.0, ge=0.0, description="Conflict detection latency in ms")
    generation_latency_ms: float = Field(default=0.0, ge=0.0, description="Answer generation latency in ms")
    grounding_latency_ms: float = Field(default=0.0, ge=0.0, description="Grounding validation latency in ms")
    total_latency_ms: float = Field(default=0.0, ge=0.0, description="Total pipeline latency in ms")
    hybrid_meta: dict[str, Any] | None = Field(
        default=None, description="Detailed hybrid retrieval diagnostics if available"
    )
    enhanced_meta: dict[str, Any] | None = Field(
        default=None, description="Detailed Phase 6 enhanced retrieval diagnostics if available"
    )
    grounding_validation: GroundingValidationResult | None = Field(
        default=None, description="Detailed Phase 7 grounding validation report"
    )
    conflict_report: ConflictReport | None = Field(
        default=None, description="Detailed Phase 7 cross-document institutional conflict report"
    )
    citations: list[CitationItem] = Field(
        default_factory=list, description="Granular Phase 8 citation items supporting factual claims"
    )
    citation_verification: CitationVerificationResult | None = Field(
        default=None, description="Detailed Phase 8 citation audit and verification report"
    )
    citation_latency_ms: float = Field(
        default=0.0, ge=0.0, description="Citation mapping, verification, and rendering latency in ms"
    )
    cited_answer: str | None = Field(
        default=None, description="Synthesized answer rendered with in-text citation markers"
    )
